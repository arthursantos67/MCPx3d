import { expect, test } from '@playwright/test'
import { createEmptyScene, createNode, validateScene } from '../../apps/web/src/three/sceneDocument.ts'
import { auroraGameplay } from '../../apps/web/src/three/world/worldAdventure.ts'
import { leaveGame } from './threeHelpers.ts'

test('sandbox harvests, crafts equipment, switches five slots and places, stores and reclaims a chest', async ({ page }) => {
  test.setTimeout(180_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (/Shader Error|GL_INVALID|Mismatch between texture/.test(message.text())) errors.push(message.text()) })
  const gameplay = auroraGameplay()
  gameplay.recipes = gameplay.recipes.filter(recipe => ['machado', 'bau'].includes(recipe.id))
  gameplay.startingItems = [{ item: 'Madeira', amount: 12 }, { item: 'Fibra', amount: 5 }]
  const floor = { ...createNode('box'), id: 'floor', name: 'Piso', position: [0, -0.1, 0], dimensions: [30, 0.2, 30] }
  const stone = { ...createNode('box'), id: 'stone', name: 'Rocha coletável', position: [0, 1, -2], dimensions: [0.8, 2, 0.8], resource: { item: 'Pedra', amount: 3, health: 1 } }
  const scene = validateScene({ ...createEmptyScene(), name: 'Construir livremente', nodes: [floor, stone], environment: { ...createEmptyScene().environment, sky: 'day', gameplay, objective: { type: 'explore', title: '', timeLimit: 0 }, player: { spawn: [0, 0, 0], yaw: 0, speed: 4.5, jumpHeight: 1, mode: 'walk', weapon: 'none' } } })
  await page.addInitScript(doc => { localStorage.setItem('modeler:workspace', 'three'); localStorage.setItem('modeler:three-scene:v1', JSON.stringify(doc)); HTMLCanvasElement.prototype.requestPointerLock = () => Promise.reject(new Error('Test drag-to-look')) }, scene)
  await page.route('http://127.0.0.1:8011/api/**', route => route.fulfill({ status: 503, body: '{}' }))
  await page.goto('/')
  await page.getByRole('button', { name: '▶ Jogar', exact: true }).click()
  const hud = page.getByRole('region', { name: 'Modo jogo' }), slots = hud.getByRole('button', { name: /^Slot / })
  await expect(slots).toHaveCount(5)
  await expect(slots.nth(0)).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.forma-prompt')).toContainText('Extrair')
  await page.keyboard.press('e')
  await expect(hud).toContainText('Pedra')
  await page.keyboard.press('b')
  const inventory = page.getByRole('dialog', { name: 'Inventário e fabricação' })
  await expect(inventory).toBeVisible()
  await inventory.getByRole('button', { name: 'Fabricar Machado de pedra', exact: true }).click()
  await expect(inventory.getByLabel('Atalho para Machado de pedra')).toHaveValue('1')
  await page.keyboard.press('Escape')
  await expect(slots.nth(1)).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('1'); await expect(slots.nth(0)).toHaveAttribute('aria-pressed', 'true')
  const canvas = page.getByRole('img', { name: 'Cena Three.js interativa' })
  await canvas.hover(); await page.mouse.wheel(0, 100)
  await expect(slots.nth(1)).toHaveAttribute('aria-pressed', 'true')
  await page.mouse.wheel(0, -100); await expect(slots.nth(0)).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('b'); await inventory.getByRole('button', { name: 'Fabricar Kit de baú', exact: true }).click()
  await expect(inventory.getByLabel('Atalho para Kit de baú')).toHaveValue('2')
  await page.keyboard.press('Escape')
  const preview = page.locator('.forma-placement')
  await expect(preview).toHaveAttribute('data-valid', 'true')
  await page.keyboard.press('r'); await page.keyboard.press('e')
  await expect(hud.getByRole('status').filter({ hasText: 'Kit de baú colocado' })).toBeVisible()
  await expect(preview).toBeHidden()
  await page.keyboard.press('1')
  const bounds = (await canvas.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2 + 54, { steps: 6 }); await page.mouse.up()
  await expect(page.locator('.forma-prompt')).toContainText('Usar · Kit de baú')
  await page.keyboard.press('e')
  await expect(inventory.getByRole('heading', { name: 'Baú', exact: true })).toBeVisible()
  await inventory.getByRole('button', { name: 'Guardar Madeira', exact: true }).click()
  await expect(inventory.getByRole('button', { name: 'Retirar Madeira', exact: true })).toBeVisible()
  await inventory.getByRole('button', { name: 'Retirar Madeira', exact: true }).click()
  await expect(inventory.getByText('Baú vazio.', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape'); await page.keyboard.press('Delete')
  await expect(hud.getByRole('status').filter({ hasText: 'Construção recolhida' })).toBeVisible()
  await page.keyboard.press('b')
  await expect(inventory.getByLabel('Atalho para Kit de baú')).toBeVisible()
  await page.screenshot({ path: '.cache/browser/three-sandbox-inventory.png' })
  await page.keyboard.press('Escape')
  await leaveGame(page)
  expect(errors).toEqual([])
})

test('minimal puzzle interface omits empty inventory, equipment bar and unnecessary meters', async ({ page }) => {
  const scene = validateScene({ ...createEmptyScene(), name: 'Enigma discreto', nodes: [{ ...createNode('box'), id: 'floor', position: [0, -0.1, 0], dimensions: [20, 0.2, 20] }],
    environment: { ...createEmptyScene().environment, gameplay: { hud: 'minimal', playStyle: 'directed', naturalResources: false, items: [], recipes: [], quests: [], startingItems: [] }, objective: { type: 'explore', title: 'Observe os símbolos', timeLimit: 0 }, player: { spawn: [0, 0, 0], yaw: 0, speed: 4, jumpHeight: 1, mode: 'walk', weapon: 'none' } } })
  await page.addInitScript(doc => { localStorage.setItem('modeler:workspace', 'three'); localStorage.setItem('modeler:three-scene:v1', JSON.stringify(doc)) }, scene)
  await page.route('http://127.0.0.1:8011/api/**', route => route.fulfill({ status: 503, body: '{}' }))
  await page.goto('/'); await page.getByRole('button', { name: '▶ Jogar', exact: true }).click()
  const hud = page.getByRole('region', { name: 'Modo jogo' })
  await expect(hud).toBeVisible()
  await expect(hud.getByRole('toolbar')).toHaveCount(0)
  await expect(hud.getByRole('meter', { name: 'Vida' })).toHaveCount(0)
  await expect(hud.getByRole('button', { name: 'Inventário · B', exact: true })).toHaveCount(0)
  await page.keyboard.press('b')
  await expect(page.getByRole('dialog', { name: 'Inventário e fabricação' })).toHaveCount(0)
  await leaveGame(page)
})
