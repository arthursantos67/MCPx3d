import * as THREE from 'three'
import { FAR, GRID, nodeSize, QUARTER, type LodField, type QuarterDraw } from './cdlod.ts'
import { APRON, TILE_SAMPLES } from './terrainTile.ts'
import type { TerrainStream } from './terrainStream.ts'
import { proceduralTexture } from '../sceneTextures.ts'

const MAX_INSTANCES = 4096
/**
 * Ground textures repeat every 1/frequency metres. Every frequency times the origin step is an integer, so moving the
 * floating origin never shifts a texture.
 */
export const ORIGIN_STEP = 256
const FREQUENCY = { base: 0.5, rock: 0.375, peak: 0.4375, micro: 2.875 }
/** Ground texture kinds the terrain samples; generated by world workers before the renderer is created. */
export const TERRAIN_TEXTURES = ['groundGrass', 'groundRock', 'groundSnow', 'groundSand'] as const

export interface TerrainLook { seaLevel: number | null; snowLine: number; range: [number, number] }
export interface TerrainRenderer {
  readonly object: THREE.Group
  /** Programs to compile before play (`renderer.compileAsync`). */
  readonly materials: THREE.Material[]
  /** A mesh drawing the terrain with its shadow-depth material, to compile that program against the shadow map target. */
  readonly shadowProxy: THREE.Mesh
  update(draws: QuarterDraw[], shadowDraws: QuarterDraw[], stream: TerrainStream, origin: [number, number], renderOrigin: [number, number], camera: THREE.Vector3): void
  setField(field: LodField): void
  dispose(): void
}

/**
 * One quarter of a node: (QUARTER+1)² vertices, cells split along the (i, j) → (i+1, j+1) diagonal, counter-clockwise
 * from above, plus a skirt: a copy of the border vertices (position.y = 1) that the shader lowers by the instance's
 * skirt depth. Patches drawn at different levels both stay within 1 px of the true surface, so the gap between them
 * is under 2 px; the skirt, textured like the ground, fills it.
 */
export function quarterGeometry(): THREE.InstancedBufferGeometry {
  const geometry = new THREE.InstancedBufferGeometry(), side = QUARTER + 1, positions: number[] = [], index: number[] = []
  for (let j = 0; j < side; j++) for (let i = 0; i < side; i++) positions.push(i, 0, j)
  for (let j = 0; j < QUARTER; j++) for (let i = 0; i < QUARTER; i++) {
    const a = j * side + i, b = a + 1, c = a + side + 1, d = a + side
    index.push(a, c, b, a, d, c)
  }
  const skirt = new Map<number, number>(), lowered = (vertex: number) => {
    if (!skirt.has(vertex)) { skirt.set(vertex, positions.length / 3); positions.push(positions[vertex * 3], 1, positions[vertex * 3 + 2]) }
    return skirt.get(vertex)!
  }
  // Each border segment (a, b) runs with the outside on its right seen from above; the strip faces outwards.
  const strip = (a: number, b: number) => { const a2 = lowered(a), b2 = lowered(b); index.push(b, a, a2, b, a2, b2) }
  for (let i = 0; i < QUARTER; i++) {
    strip(i + 1, i)
    strip(QUARTER * side + i, QUARTER * side + i + 1)
    strip(i * side, (i + 1) * side)
    strip((i + 1) * side + QUARTER, i * side + QUARTER)
  }
  geometry.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3))
  geometry.setIndex(index)
  geometry.setAttribute('terrainNode', new THREE.InstancedBufferAttribute(new Float32Array(MAX_INSTANCES * 4), 4).setUsage(THREE.DynamicDrawUsage))
  geometry.setAttribute('terrainTexel', new THREE.InstancedBufferAttribute(new Float32Array(MAX_INSTANCES * 3), 3).setUsage(THREE.DynamicDrawUsage))
  geometry.setAttribute('terrainRange', new THREE.InstancedBufferAttribute(new Float32Array(MAX_INSTANCES * 4), 4).setUsage(THREE.DynamicDrawUsage))
  geometry.instanceCount = 0
  geometry.boundingSphere = new THREE.Sphere(new THREE.Vector3(), Infinity)
  return geometry
}

const vertexCommon = `
uniform highp sampler2DArray terrainHeights;
uniform vec3 terrainCamera;
uniform float terrainMorphKeep;
attribute vec4 terrainNode;
attribute vec3 terrainTexel;
attribute vec4 terrainRange;
varying vec3 vTerrainWorld;
varying vec3 vTerrainNormal;
float terrainFetch(vec2 cell) { return texelFetch(terrainHeights, ivec3(int(cell.x) + ${APRON}, int(cell.y) + ${APRON}, int(terrainTexel.x + 0.5)), 0).r; }
vec3 terrainSlope(vec2 cell, float spacing) {
  return normalize(vec3(terrainFetch(cell - vec2(1.0, 0.0)) - terrainFetch(cell + vec2(1.0, 0.0)), 2.0 * spacing, terrainFetch(cell - vec2(0.0, 1.0)) - terrainFetch(cell + vec2(0.0, 1.0))));
}
// CDLOD morph: odd vertices slide onto their lower even neighbour as the distance approaches the range (bilinear between
// the node's corner ranges), so at the end of the range the patch is exactly the next coarser mesh.
void terrainVertex(out vec3 terrainOut, out vec3 normal) {
  vec2 cell = position.xz + terrainTexel.yz;
  float skirt = position.y * terrainNode.w;
  float spacing = terrainNode.z;
  float height = terrainFetch(cell);
  vec2 plane = terrainNode.xy + cell * spacing, along = cell / ${GRID}.0;
  float end = mix(mix(terrainRange.x, terrainRange.y, along.x), mix(terrainRange.z, terrainRange.w, along.x), along.y), start = end * terrainMorphKeep;
  float morph = clamp((distance(terrainCamera, vec3(plane.x, height, plane.y)) - start) / max(end - start, 1e-3), 0.0, 1.0);
  vec2 odd = mod(cell, 2.0), target = cell - odd;
  vec2 moved = cell - odd * morph;
  terrainOut = vec3(terrainNode.x + moved.x * spacing, mix(height, terrainFetch(target), morph) - skirt, terrainNode.y + moved.y * spacing);
  normal = normalize(mix(terrainSlope(cell, spacing), terrainSlope(target, spacing), morph));
}
`

function patchDepth(material: THREE.Material, uniforms: Record<string, THREE.IUniform>) {
  material.onBeforeCompile = (shader) => {
    Object.assign(shader.uniforms, uniforms)
    shader.vertexShader = shader.vertexShader.replace('#include <common>', `#include <common>\n${vertexCommon}`)
      .replace('#include <begin_vertex>', 'vec3 transformed; vec3 terrainNormalOut; terrainVertex(transformed, terrainNormalOut); vTerrainWorld = transformed; vTerrainNormal = terrainNormalOut;')
  }
  material.customProgramCacheKey = () => 'world-terrain-depth-v1'
}

export function createTerrainRenderer(stream: TerrainStream, look: TerrainLook, anisotropy = 4): TerrainRenderer {
  const heights = new THREE.DataArrayTexture(stream.data, TILE_SAMPLES, TILE_SAMPLES, stream.capacity)
  heights.format = THREE.RedFormat
  heights.type = THREE.FloatType
  heights.internalFormat = 'R32F'
  heights.minFilter = heights.magFilter = THREE.NearestFilter
  heights.generateMipmaps = false
  heights.needsUpdate = true
  const uniforms: Record<string, THREE.IUniform> = { terrainHeights: { value: heights }, terrainCamera: { value: new THREE.Vector3() }, terrainMorphKeep: { value: 0.7 } }
  let field: LodField | null = null
  const texture = (kind: Parameters<typeof proceduralTexture>[0], channel: 'map' | 'normal') => {
    const result = proceduralTexture(kind, channel)
    result.wrapS = result.wrapT = THREE.RepeatWrapping
    result.anisotropy = anisotropy
    return result
  }
  const textures = { base: texture('groundGrass', 'map'), baseNormal: texture('groundGrass', 'normal'), rock: texture('groundRock', 'map'), rockNormal: texture('groundRock', 'normal'),
    peak: texture('groundSnow', 'map'), sand: texture('groundSand', 'map') }
  const material = new THREE.MeshStandardMaterial({ color: '#ffffff', roughness: 0.92, metalness: 0, map: textures.base, normalMap: textures.baseNormal, normalScale: new THREE.Vector2(0.65, 0.65) })
  // Grass, rock, snow and sand, the meadow/alpine colours of 1.x biome terrains (linear).
  const palette = ['#5d7d42', '#7a7166', '#eef1f4', '#c9b98d'].map((hex) => new THREE.Color(hex))
  const look4 = new THREE.Vector4(look.seaLevel ?? -1e6, look.snowLine, look.range[0], look.range[1])
  material.onBeforeCompile = (shader) => {
    Object.assign(shader.uniforms, uniforms, { terrainRock: { value: textures.rock }, terrainRockNormal: { value: textures.rockNormal }, terrainPeak: { value: textures.peak }, terrainSand: { value: textures.sand }, terrainLook: { value: look4 },
      terrainPalette: { value: palette } })
    shader.vertexShader = shader.vertexShader.replace('#include <common>', `#include <common>\n${vertexCommon}`)
      .replace('#include <beginnormal_vertex>', 'vec3 terrainPosition; vec3 objectNormal; terrainVertex(terrainPosition, objectNormal); vTerrainWorld = terrainPosition; vTerrainNormal = objectNormal;')
      .replace('#include <begin_vertex>', 'vec3 transformed = terrainPosition;')
    shader.fragmentShader = shader.fragmentShader.replace('#include <common>', `#include <common>
uniform sampler2D terrainRock;
uniform sampler2D terrainRockNormal;
uniform sampler2D terrainPeak;
uniform sampler2D terrainSand;
uniform vec4 terrainLook;
uniform vec3 terrainPalette[4];
varying vec3 vTerrainWorld;
varying vec3 vTerrainNormal;
vec3 terrainWeights() {
  vec3 n = normalize(vTerrainNormal);
  float rock = smoothstep(0.82, 0.62, n.y);
  float peak = smoothstep(terrainLook.y - 25.0, terrainLook.y + 25.0, vTerrainWorld.y) * smoothstep(0.55, 0.75, n.y);
  float sand = smoothstep(terrainLook.x + 4.0, terrainLook.x + 1.0, vTerrainWorld.y);
  return vec3(rock, peak, sand);
}`)
      .replace('#include <map_fragment>', `
vec3 groundWeights = terrainWeights();
vec2 groundUv = vTerrainWorld.xz * ${FREQUENCY.base.toFixed(4)};
vec3 groundColor = texture2D(map, groundUv).rgb, groundMacro = terrainPalette[0];
groundColor = mix(groundColor, texture2D(terrainSand, vTerrainWorld.xz * ${FREQUENCY.base.toFixed(4)}).rgb, groundWeights.z);
groundMacro = mix(groundMacro, terrainPalette[3], groundWeights.z);
groundColor = mix(groundColor, texture2D(terrainRock, vTerrainWorld.xz * ${FREQUENCY.rock.toFixed(4)}).rgb, groundWeights.x);
groundMacro = mix(groundMacro, terrainPalette[1], groundWeights.x);
groundColor = mix(groundColor, texture2D(terrainPeak, vTerrainWorld.xz * ${FREQUENCY.peak.toFixed(4)}).rgb, groundWeights.y);
groundMacro = mix(groundMacro, terrainPalette[2], groundWeights.y);
// Macro colour from the ground layer; the textures add fibres, grains and fissures, as in 1.x biome terrains.
float groundMicro = texture2D(map, vTerrainWorld.xz * ${FREQUENCY.micro.toFixed(4)} + vec2(0.31, 0.57)).g;
diffuseColor.rgb = groundMacro * clamp(vec3(0.66) + groundColor * 0.53 + groundMicro * 0.1, vec3(0.66), vec3(1.24));`)
      .replace('#include <normal_fragment_maps>', `
vec3 groundN = mix(texture2D(normalMap, groundUv).xyz * 2.0 - 1.0, texture2D(terrainRockNormal, vTerrainWorld.xz * ${FREQUENCY.rock.toFixed(4)}).xyz * 2.0 - 1.0, groundWeights.x);
groundN.xy *= normalScale;
normal = normalize(getTangentFrame(-vViewPosition, normal, groundUv) * normalize(groundN));`)
  }
  material.customProgramCacheKey = () => 'world-terrain-v1'
  const geometry = quarterGeometry(), shadowGeometry = quarterGeometry()
  const mesh = new THREE.Mesh(geometry, material)
  mesh.frustumCulled = false
  mesh.receiveShadow = true
  mesh.castShadow = false
  mesh.matrixAutoUpdate = false
  const depth = new THREE.MeshDepthMaterial({ depthPacking: THREE.RGBADepthPacking }), distance = new THREE.MeshDistanceMaterial()
  patchDepth(depth, uniforms)
  patchDepth(distance, uniforms)
  // The shadow pass draws back faces of single-sided casters (three sets this on every shadow render); match it here
  // so the program compiled ahead of time is the one the pass uses.
  depth.side = THREE.BackSide
  // The near-player shadow caster draws nothing in colour passes (no instances there); shadow passes skip onBeforeRender.
  const caster = new THREE.Mesh(shadowGeometry, material)
  let casterCount = 0
  caster.onBeforeRender = () => { casterCount = shadowGeometry.instanceCount; shadowGeometry.instanceCount = 0 }
  caster.onAfterRender = () => { shadowGeometry.instanceCount = casterCount }
  caster.customDepthMaterial = depth
  caster.customDistanceMaterial = distance
  caster.frustumCulled = false
  caster.castShadow = true
  caster.receiveShadow = false
  caster.matrixAutoUpdate = false
  const object = new THREE.Group()
  object.name = 'Terreno do mundo'
  object.add(mesh, caster)
  const fill = (target: THREE.InstancedBufferGeometry, draws: QuarterDraw[], origin: [number, number], renderOrigin: [number, number]) => {
    const node = target.getAttribute('terrainNode') as THREE.InstancedBufferAttribute, texel = target.getAttribute('terrainTexel') as THREE.InstancedBufferAttribute
    const range = target.getAttribute('terrainRange') as THREE.InstancedBufferAttribute
    const nodes = node.array as Float32Array, texels = texel.array as Float32Array, ranges = range.array as Float32Array
    let count = 0
    for (const draw of draws) {
      const tile = stream.tile(draw.level, draw.ix, draw.iz)
      if (!tile || count >= MAX_INSTANCES) continue
      const size = nodeSize(draw.level)
      nodes[count * 4] = origin[0] + draw.ix * size - renderOrigin[0]
      nodes[count * 4 + 1] = origin[1] + draw.iz * size - renderOrigin[1]
      nodes[count * 4 + 2] = size / GRID
      nodes[count * 4 + 3] = field?.skirt(draw.level, draw.ix, draw.iz) ?? 1
      texels[count * 3] = tile.layer
      texels[count * 3 + 1] = (draw.quarter & 1) * QUARTER
      texels[count * 3 + 2] = (draw.quarter >> 1) * QUARTER
      for (let corner = 0; corner < 4; corner++) ranges[count * 4 + corner] = Math.min(FAR, field?.corner(draw.level, draw.ix + (corner & 1), draw.iz + (corner >> 1)) ?? FAR)
      count++
    }
    target.instanceCount = count
    node.clearUpdateRanges(); node.addUpdateRange(0, count * 4); node.needsUpdate = true
    texel.clearUpdateRanges(); texel.addUpdateRange(0, count * 3); texel.needsUpdate = true
    range.clearUpdateRanges(); range.addUpdateRange(0, count * 4); range.needsUpdate = true
  }
  const shadowProxy = new THREE.Mesh(shadowGeometry, depth)
  shadowProxy.frustumCulled = false
  return {
    object, materials: [material, depth, distance], shadowProxy,
    update(draws, shadowDraws, source, origin, renderOrigin, camera) {
      const dirty = source.takeDirty()
      if (dirty.length) { for (const layer of dirty) heights.addLayerUpdate(layer); heights.needsUpdate = true }
      uniforms.terrainCamera.value.copy(camera)
      fill(geometry, draws, origin, renderOrigin)
      fill(shadowGeometry, shadowDraws, origin, renderOrigin)
    },
    setField(next) { field = next; uniforms.terrainMorphKeep.value = 1 - next.morphFraction },
    dispose() {
      geometry.dispose(); shadowGeometry.dispose(); material.dispose(); depth.dispose(); distance.dispose(); heights.dispose()
      for (const value of Object.values(textures)) value.dispose()
    },
  }
}
