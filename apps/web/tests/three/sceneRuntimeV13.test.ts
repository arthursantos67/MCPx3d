import assert from 'node:assert/strict'
import { test } from 'node:test'
import { createEmptyScene, createNode, validateScene, type SceneInteraction, type SceneNode, type SceneObjective } from '../../src/three/sceneDocument.ts'
import { activeEnemy, advanceRuntime, checkOutcome, createRuntime, damageEnemy, damagePlayer, defeatEnemy, dialogueState, drainEvents, enemyHealth, interactionAvailable, interactionBlocked,
  launchVelocity, objectiveLimit, objectiveStatus, playerModifiers, reachCheckpoint, reachGoal, triggerInteraction, updateProximity } from '../../src/three/sceneRuntime.ts'

const act = (id: string, interaction: Partial<SceneInteraction>): SceneNode => ({ ...createNode('box'), id, name: id,
  interaction: { trigger: 'click', key: '', radius: 3, action: 'message', targetId: null, message: '', ...interaction } })
const foe = (id: string, extra: Record<string, unknown> = {}): SceneNode => ({ ...createNode('group'), id, name: id, behavior: { type: 'enemy', speed: 2, range: 8, damage: 20, ...extra } })
const scene = (nodes: SceneNode[], objective?: SceneObjective) => validateScene({ ...createEmptyScene(), nodes, environment: { ...createEmptyScene().environment, ...(objective ? { objective } : {}) } })
const kinds = (runtime: ReturnType<typeof createRuntime>) => drainEvents(runtime).map((event) => event.kind)

test('inventory: items count as collectibles, required items unlock without being consumed', () => {
  const runtime = createRuntime(scene([act('key', { action: 'collect', item: 'Chave dourada' }), act('coin', { action: 'collect' }),
    act('door', { action: 'message', requires: 'Chave dourada', message: 'A porta abriu.' })]))
  assert.equal(runtime.collectibles, 2)
  assert.equal(interactionBlocked(runtime, runtime.byId.get('door')!), 'Precisa de: Chave dourada')
  assert.equal(triggerInteraction(runtime, 'door'), 'Precisa de: Chave dourada')
  assert.ok(runtime.blocked.has('door'))
  assert.deepEqual(kinds(runtime), ['locked'])
  assert.match(triggerInteraction(runtime, 'key')!, /Chave dourada obtido · 1\/2/)
  assert.equal(runtime.items.get('Chave dourada'), 1)
  assert.equal(triggerInteraction(runtime, 'door'), 'A porta abriu.')
  assert.equal(runtime.blocked.has('door'), false)
  assert.deepEqual(kinds(runtime), ['collect', 'unlock', 'message'])
  triggerInteraction(runtime, 'door')
  assert.deepEqual(kinds(runtime), ['message'], 'unlock plays only once')
  assert.equal(runtime.items.get('Chave dourada'), 1)
  assert.equal(runtime.score, 10)
})

test('a locked proximity trigger re-arms after leaving and acts once the item is held', () => {
  const runtime = createRuntime(scene([act('gate', { trigger: 'proximity', radius: 2, action: 'message', requires: 'Runa', message: 'Passagem livre' }), act('rune', { action: 'collect', item: 'Runa' })]))
  const positions = new Map([['gate', [0, 0, 0] as [number, number, number]]])
  assert.deepEqual(updateProximity(runtime, [0, 0, 1], positions), ['Precisa de: Runa'])
  triggerInteraction(runtime, 'rune')
  assert.deepEqual(updateProximity(runtime, [0, 0, 1], positions), [])
  updateProximity(runtime, [0, 0, 5], positions)
  assert.deepEqual(updateProximity(runtime, [0, 0, 1], positions), ['Passagem livre'])
})

test('heal restores up to the maximum and is consumed; full health keeps the pickup', () => {
  const runtime = createRuntime(scene([act('potion', { action: 'heal' }), act('big', { action: 'heal', amount: 500 })]))
  assert.equal(triggerInteraction(runtime, 'potion'), 'Vida já está cheia.')
  assert.ok(interactionAvailable(runtime, runtime.byId.get('potion')!))
  damagePlayer(runtime, 40)
  assert.equal(triggerInteraction(runtime, 'potion'), '+25 de vida')
  assert.equal(runtime.health, 85)
  assert.ok(runtime.hidden.has('potion') && !interactionAvailable(runtime, runtime.byId.get('potion')!))
  assert.equal(runtime.collected.size, 0, 'heals are not collectibles')
  triggerInteraction(runtime, 'big')
  assert.equal(runtime.health, 100)
  assert.equal(runtime.score, 10)
  assert.deepEqual(kinds(runtime), ['hurt', 'heal', 'heal'])
})

test('powerups modify the player for a while; shield blocks damage', () => {
  const runtime = createRuntime(scene([act('boots', { action: 'powerup' }), act('aegis', { action: 'powerup', power: 'shield', amount: 3 }), act('fist', { action: 'powerup', power: 'strength' }), act('spring', { action: 'powerup', power: 'jump' })]))
  assert.deepEqual(playerModifiers(runtime), { speed: 1, jump: 1, damage: 1, shield: false })
  assert.equal(triggerInteraction(runtime, 'boots'), 'Velocidade por 10 s')
  triggerInteraction(runtime, 'aegis'); triggerInteraction(runtime, 'fist'); triggerInteraction(runtime, 'spring')
  assert.deepEqual(playerModifiers(runtime), { speed: 1.6, jump: 1.6, damage: 2, shield: true })
  drainEvents(runtime)
  assert.equal(damagePlayer(runtime, 50), false)
  assert.equal(runtime.health, 100)
  assert.deepEqual(kinds(runtime), ['shield'])
  advanceRuntime(runtime, 3.5)
  assert.equal(playerModifiers(runtime).shield, false)
  assert.deepEqual(drainEvents(runtime), [{ kind: 'powerdown', id: 'shield' }])
  assert.equal(damagePlayer(runtime, 50), true)
  assert.equal(runtime.health, 50)
  advanceRuntime(runtime, 7)
  assert.deepEqual(playerModifiers(runtime), { speed: 1, jump: 1, damage: 1, shield: false })
  assert.equal(runtime.score, 20)
})

test('dialogue cycles through lines separated by |', () => {
  const runtime = createRuntime(scene([act('sage', { action: 'dialogue', message: 'Olá, viajante. | O portal fica ao norte.|Boa sorte!' }), act('mute', { action: 'dialogue' })]))
  assert.deepEqual(dialogueState(runtime, 'sage'), { index: -1, total: 3, line: null })
  assert.deepEqual(['sage', 'sage', 'sage', 'sage'].map((id) => triggerInteraction(runtime, id)), ['Olá, viajante.', 'O portal fica ao norte.', 'Boa sorte!', 'Olá, viajante.'])
  assert.deepEqual(dialogueState(runtime, 'sage'), { index: 0, total: 3, line: 'Olá, viajante.' })
  assert.equal(triggerInteraction(runtime, 'mute'), null)
  assert.equal(dialogueState(runtime, 'missing'), null)
  assert.equal(kinds(runtime).filter((kind) => kind === 'dialogue').length, 4)
})

test('enemies take several hits, delayed enemies spawn later and still count, score rewards defeats', () => {
  const runtime = createRuntime(scene([foe('ogre', { health: 3 }), foe('late', { delay: 5 })], { type: 'defeatEnemies', title: '', timeLimit: 0 }))
  assert.deepEqual(enemyHealth(runtime, 'ogre'), { health: 3, max: 3 })
  assert.equal(damageEnemy(runtime, 'ogre', 1), 'hit')
  assert.equal(damageEnemy(runtime, 'ogre', 0), null)
  assert.deepEqual(enemyHealth(runtime, 'ogre'), { health: 2, max: 3 })
  assert.equal(damageEnemy(runtime, 'ogre', 2), 'defeated')
  assert.equal(damageEnemy(runtime, 'ogre', 1), null)
  assert.equal(runtime.enemies.length, 2)
  assert.equal(activeEnemy(runtime, 'late'), false)
  assert.ok(runtime.hidden.has('late'))
  assert.equal(damageEnemy(runtime, 'late', 5), null)
  assert.equal(defeatEnemy(runtime, 'late'), false)
  checkOutcome(runtime)
  assert.equal(runtime.outcome, 'playing')
  advanceRuntime(runtime, 5)
  assert.equal(activeEnemy(runtime, 'late'), true)
  assert.equal(runtime.hidden.has('late'), false)
  assert.equal(damageEnemy(runtime, 'late', 1), 'defeated')
  checkOutcome(runtime)
  assert.equal(runtime.outcome, 'won')
  assert.deepEqual(kinds(runtime), ['hit', 'defeat', 'spawn', 'defeat', 'victory'])
  assert.equal(runtime.score, 50 + 50 + 100)
})

test('survive wins when the time runs out while alive; other objectives lose on timeout', () => {
  const runtime = createRuntime(scene([foe('wolf')], { type: 'survive', title: '', timeLimit: 0 }))
  assert.equal(objectiveLimit(runtime), 60)
  advanceRuntime(runtime, 17.5)
  assert.equal(objectiveStatus(runtime).text, 'Sobreviva · 43 s')
  assert.match(reachGoal(runtime)!, /fechado/)
  checkOutcome(runtime)
  assert.equal(runtime.outcome, 'playing')
  advanceRuntime(runtime, 43)
  checkOutcome(runtime)
  assert.equal(runtime.outcome, 'won')
  assert.equal(runtime.score, 100)
  const dead = createRuntime(scene([foe('wolf')], { type: 'survive', title: '', timeLimit: 10 }))
  damagePlayer(dead, 100)
  assert.deepEqual(kinds(dead), ['defeat-player'])
  advanceRuntime(dead, 11)
  checkOutcome(dead)
  assert.equal(dead.outcome, 'playing', 'the viewport respawns a defeated player before the timer is checked')
  const timed = createRuntime(scene([act('coin', { action: 'collect' })], { type: 'collectAll', title: '', timeLimit: 5 }))
  advanceRuntime(timed, 6)
  checkOutcome(timed)
  assert.equal(timed.outcome, 'lost')
  assert.deepEqual(kinds(timed), ['timeout'])
})

test('victory bonus counts remaining health and seconds; checkpoints and launchers', () => {
  const runtime = createRuntime(scene([act('coin', { action: 'collect' })], { type: 'collectAll', title: '', timeLimit: 30 }))
  damagePlayer(runtime, 50)
  advanceRuntime(runtime, 10.4)
  triggerInteraction(runtime, 'coin')
  checkOutcome(runtime)
  assert.equal(runtime.score, 10 + 50 + 2 * 19)
  assert.equal(reachCheckpoint(runtime, 'flag', [1, 2, 3]), false, 'no checkpoints after the level ends')
  const fresh = createRuntime(scene([]))
  assert.equal(reachCheckpoint(fresh, 'flag', [1, 2, 3]), true)
  assert.equal(reachCheckpoint(fresh, 'flag', [4, 5, 6]), false)
  assert.deepEqual(fresh.checkpoint, [1, 2, 3])
  assert.deepEqual(drainEvents(fresh), [{ kind: 'checkpoint', id: 'flag' }])
  assert.deepEqual(drainEvents(fresh), [])
  assert.ok(Math.abs(launchVelocity({ range: 3 }) - 12) < 1e-9)
  assert.ok(Math.abs(launchVelocity({ range: 2 }, 9.81) - Math.sqrt(2 * 9.81 * 2)) < 1e-9)
})
