import { writeFile } from 'node:fs/promises'
import { buildValleyScene } from '../apps/web/src/three/sceneShowcase.ts'
import { inspectSceneGeometry } from '../apps/web/src/three/sceneInspection.ts'
import { auditScene, prepareScene, settleLayout } from '../apps/web/src/three/sceneLayout.ts'

const original = buildValleyScene()
let scene = prepareScene(original).document
for (let pass = 0; pass < 4; pass++) {
  const inspection = inspectSceneGeometry(scene)
  if (!inspection.complete) throw new Error('Showcase inspection was incomplete.')
  if (!inspection.intersections.length) break
  const next = settleLayout(scene, inspection).document
  if (next === scene) break
  scene = next
}
const inspection = inspectSceneGeometry(scene), audit = auditScene(scene, inspection)
if (!inspection.complete || audit.total) throw new Error(`Showcase still has ${audit.total} quality issues.`)
const initial = new Map(original.nodes.map(node => [node.id, node]))
const placements = Object.fromEntries(scene.nodes.filter(node => JSON.stringify(node.position) !== JSON.stringify(initial.get(node.id)?.position)).map(node => [node.id, node.position]))
const terrain = scene.nodes.find(node => node.id === 'ground')
const pads = JSON.stringify(terrain.geometry.pads) === JSON.stringify(initial.get('ground').geometry.pads) ? null : terrain.geometry.pads
const ids = new Set(scene.nodes.map(node => node.id)), removed = original.nodes.filter(node => !ids.has(node.id)).map(node => node.id)
const output = `// Generated by scripts/bake-three-showcase.mjs. Regenerate after editing the reference level.\nexport const valleyPlacements: Record<string, [number, number, number]> = ${JSON.stringify(placements, null, 2)}\nexport const valleyPads: number[][] | null = ${JSON.stringify(pads)}\nexport const valleyRemoved: string[] = ${JSON.stringify(removed)}\n`
await writeFile(new URL('../apps/web/src/three/sceneShowcaseLayout.ts', import.meta.url), output, 'utf8')
console.log(`Showcase: ${scene.nodes.length} objects, ${Object.keys(placements).length} adjusted placements, ${removed.length} removed, no audit issues.`)
